export type Locale = (typeof LOCALES)[number];

/** Each language in its own script, for the switcher and the host's setting. */
export const LOCALE_NAMES: Record<Locale, string> = { en: "English", hi: "हिन्दी", ta: "தமிழ்", te: "తెలుగు", kn: "ಕನ್ನಡ" };

export const isLocale = (v: unknown): v is Locale => typeof v === "string" && (LOCALES as readonly string[]).includes(v);

/** A valid `?lang=` wins, then the host's default, then English. */
export function resolveLocale(lang: unknown, hostDefault: string | null | undefined): Locale {
  if (isLocale(lang)) return lang;
  return isLocale(hostDefault) ? hostDefault : "en";
}

/** The Intl tag for dates and times; Latin digits in every language. */
export const intlTag = (locale: Locale) => (locale === "en" ? "en-IN" : `${locale}-IN-u-nu-latn`);

