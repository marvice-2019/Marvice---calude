export const CATALOGS: Record<Locale, Catalog> = { en, hi, ta, te, kn };

/** The line for `key` in `locale`, with each `{name}` replaced from `vars`; unknown placeholders are left as written. */
export function t(locale: Locale, key: GuestKey, vars: Record<string, string | number> = {}): string {
  return CATALOGS[locale][key].replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

/** Like t, but placeholders can be elements (a live clock time, a bold brand name). */
export function tNodes(locale: Locale, key: GuestKey, nodes: Record<string, ReactNode>): ReactNode[] {
  return CATALOGS[locale][key].split(/(\{\w+\})/).map((part, i) => {
    const name = /^\{(\w+)\}$/.exec(part)?.[1];
    return createElement(Fragment, { key: i }, name && name in nodes ? nodes[name] : part);
  });
}

