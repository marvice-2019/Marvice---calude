// B-2 end to end over HTTP: weekly series booking, manage page, cancel later weeks. Usage: node e2e/e2e-recurring.mjs <port> <database-url>
import pg from "pg";
const [port, databaseUrl] = process.argv.slice(2);
const B = `http://localhost:${port}`;
const pool = new pg.Pool({ connectionString: databaseUrl });
let fail = 0;
const check = (ok, label) => { if (!ok) fail++; console.log(`${ok ? "OK  " : "FAIL"} ${label}`); };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
for (let i = 0; i < 40; i++) { try { await fetch(B); break; } catch { await sleep(500); } }
const ip = "203.0.113.77";
const post = (path, body) => fetch(B + path, { method: "POST", headers: { "content-type": "application/json", "x-forwarded-for": ip }, body: JSON.stringify(body) });
const page = async (p) => (await (await fetch(B + p)).text()).replace(/<!-- -->/g, "");

await pool.query("update event_types set max_repeats = 4 where slug = 'coaching' and user_id = (select id from users where slug = 'priya')");
const WEEK = 7 * 86400000;
const now = Date.now();
const slotsRes = await (await fetch(`${B}/api/slots?slug=priya&event=coaching&from=${new Date(now).toISOString()}&to=${new Date(now + 50 * 86400000).toISOString()}&tz=Asia/Kolkata`)).json();
const open = new Set(slotsRes.slots.map((s) => new Date(s).getTime()));
const start = slotsRes.slots.find((s) => [1, 2].every((w) => open.has(new Date(s).getTime() + w * WEEK)));
check(Boolean(start), "a time open three weeks running");
const base = { slug: "priya", event: "coaching", start, name: "Series Guest", email: "series@example.com", timezone: "Asia/Kolkata", answers: {} };
const qs = (await pool.query("select id from custom_questions where event_type_id = (select id from event_types where slug='coaching' and user_id=(select id from users where slug='priya')) and required")).rows;
for (const q of qs) base.answers[q.id] = "Weekly practice";
const tooMany = await post("/api/bookings", { ...base, weeks: 5, idempotencyKey: "e2e-series-too-many" });
check(tooMany.status === 400, `5 weeks refused (allowed 4): ${tooMany.status}`);
const ok = await post("/api/bookings", { ...base, weeks: 3, idempotencyKey: "e2e-series-0001" });
const body = await ok.json();
check(ok.status === 201, `3 weeks booked: ${ok.status}`);
const { rows } = await pool.query("select b.id, b.series_index, b.start_at, i.manage_token from bookings b join invitees i on i.booking_id = b.id where b.series_id = $1 order by b.series_index", [body.bookingId]);
check(rows.length === 3 && rows.every((r, i) => new Date(r.start_at).getTime() === new Date(start).getTime() + i * WEEK), "three weeks, a week apart, in one series");
const emails = (await pool.query("select kind, count(*)::int as n from notifications where booking_id = any($1) and channel = 'email' group by kind order by kind", [rows.map((r) => r.id)])).rows;
check(emails.find((e) => e.kind === "booked_guest")?.n === 1, "one confirmation for the whole series");
const manage = await page(`/b/${rows[1].manage_token}`);
check(manage.includes("Week 2 of 3"), "manage page says Week 2 of 3");
check(manage.includes("Also cancel the next week"), "manage page offers cancelling the later week");
const cancel = await post(`/api/b/${rows[1].manage_token}/cancel`, { laterWeeks: true });
check(cancel.status === 200, `cancel week 2 and later: ${cancel.status}`);
const states = (await pool.query("select status from bookings where series_id = $1 order by series_index", [body.bookingId])).rows.map((r) => r.status);
check(JSON.stringify(states) === JSON.stringify(["confirmed", "cancelled", "cancelled"]), `week 1 kept, 2 and 3 cancelled: ${states}`);
await pool.end();
console.log(fail ? `${fail} FAILED` : "ALL OK");
process.exit(fail ? 1 : 0);
